let language = 'zh-CN';
const listeners = new Set();
export function getLanguage() { return language; }
export function t(key, values = {}, selected = language) {
  const template = messages[key]?.[selected] || messages[key]?.['zh-CN'] || key;
  return template.replace(/\{(\w+)\}/g, (whole, name) => Object.hasOwn(values, name) ? String(values[name]) : whole);
}
export function localizeError(message, selected = language) {
  if (selected !== 'en' || typeof message !== 'string') return message;
  for (const [zh, en] of errorPairs) if (message === zh) return en;
  for (const [zh, en] of errorPairs) {
    const keys = []; let pattern = '', last = 0;
    for (const match of zh.matchAll(/\{(\w+)\}/g)) {
      keys.push(match[1]); pattern += escapeRegex(zh.slice(last, match.index)) + '(.+?)'; last = match.index + match[0].length;
    }
    if (!keys.length) continue;
    const match = new RegExp('^' + pattern + escapeRegex(zh.slice(last)) + '$').exec(message);
    if (match) return en.replace(/\{(\w+)\}/g, (_, name) => localizeError(match[keys.indexOf(name) + 1], selected));
  }
  return message;
}
function escapeRegex(value) { return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
export function onLanguageChange(listener) { listeners.add(listener); return () => listeners.delete(listener); }
export function applyLanguage(root = globalThis.document) {
  if (!root) return;
  if (root.documentElement) root.documentElement.lang = language;
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll('[data-i18n-label]')) node.setAttribute('aria-label', t(node.dataset.i18nLabel));
}
export function setLanguage(value) { language = value === 'en' ? 'en' : 'zh-CN'; applyLanguage(); for (const listener of listeners) listener(); }
